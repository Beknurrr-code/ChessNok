// === Обновлённая база знаний Chessnok Assistant ===
function getBotResponse(input) {
  const text = input.toLowerCase();

  if (text.includes("привет") || text.includes("здравствуй"))
    return "Привет! Готов помочь по шахматам. Спроси меня о правилах, дебютах или стратегиях.";

  if (text.includes("дебют"))
    return "Дебют — начальная стадия партии. Главное: захватить центр, развить фигуры и рокироваться. Примеры: Итальянская партия, Сицилианская защита.";

  if (text.includes("гамбит"))
    return "Гамбит — это жертва пешки или фигуры в дебюте ради атаки. Популярные: Гамбит короля, Гамбит Эванса, Ферзевый гамбит.";

  if (text.includes("миттельшпиль"))
    return "Миттельшпиль — это середина партии. Здесь важны тактика, активные фигуры и контроль ключевых полей.";

  if (text.includes("эндшпиль"))
    return "Эндшпиль — это окончание партии. Нужно активизировать короля и использовать проходные пешки.";

  if (text.includes("рокировка"))
    return "Рокировка — это ход, при котором король и ладья меняются местами. Это делается один раз за игру для безопасности короля.";

  if (text.includes("цейтнот"))
    return "Цейтнот — это нехватка времени. Лучше играть ближе к основам и не рисковать, когда таймер поджимает.";

  if (text.includes("пат"))
    return "Пат — это ничья, когда у игрока нет ходов, но король не под шахом.";

  if (text.includes("ничья"))
    return "Ничья бывает по пату, повтору позиции, по 50 ходам без взятий и по договорённости.";

  if (text.includes("ферзь"))
    return "Ферзь — самая сильная фигура. Ходит по вертикали, горизонтали и диагонали.";

  if (text.includes("ладья"))
    return "Ладья — ходит только по вертикали и горизонтали. Играет ключевую роль в атаке и эндшпиле.";

  if (text.includes("слон"))
    return "Слон — ходит по диагонали. У каждого игрока есть белопольный и чернопольный слон.";

  if (text.includes("конь"))
    return "Конь — фигура, ходит буквой Г и прыгает через другие. Отличен для вилок!";

  if (text.includes("пешка"))
    return "Пешка — самая слабая, но может дойти до конца и превратиться в любую фигуру (обычно ферзя).";

  if (text.includes("шах"))
    return "Шах — угроза королю. Нужно либо уйти, либо закрыться, либо взять фигуру.";

  if (text.includes("мат"))
    return "Мат — это шах, от которого нельзя защититься. Цель игры — поставить мат сопернику.";

  if (text.includes("центр"))
    return "Контроль над центром (поля e4, d4, e5, d5) — ключ к успеху в дебюте.";

  if (text.includes("развитие"))
    return "Развивай фигуры быстро: не ходи одной и той же фигурой дважды в дебюте.";

  if (text.includes("таймер") || text.includes("время"))
    return "Следи за временем: блиц — 3-5 мин, пуля — до 1 мин, классика — 15+."

  if (text.includes("флаг"))
    return "Флаг — это когда у игрока закончилось время. В блице это означает проигрыш, даже если у тебя преимущество.";

  if (text.includes("f7"))
    return "Поле f7 — слабое у чёрных (у белых — f2). Частая цель атак в дебюте!";

  if (text.includes("ловушка"))
    return "Шахматная ловушка — это тактический трюк. Пример: Ловушка Легаля, Ловушка в сицилианке.";

  if (text.includes("гроссмейстер"))
    return "Гроссмейстер — это высшее шахматное звание. Требует высоких рейтингов и сильной игры в турнирах.";

  if (text.includes("рейтинг"))
    return "Обычно рейтинг новичка — 600–1000, любителя — 1200–1600, эксперта — 1800+, мастер — 2000+, гроссмейстер — 2500+."

  if (text.includes("чемпион"))
    return "Чемпионы мира: Стейниц, Алехин, Капабланка, Фишер, Каспаров, Карпов, Карлсен и другие.";

  if (text.includes("история"))
    return "Шахматы возникли в Индии (чатуранга), через Персию стали шатранджем, а в Европе приняли современный вид.";

  if (text.includes("обучение") || text.includes("учиться") || text.includes("как играть"))
    return "Изучи основы: как ходят фигуры, что такое шах и мат, потом переходи к дебютам и тактике."

  return "Извини, я пока не знаю, как на это ответить. Попробуй спросить про дебют, рокировку, ферзя или эндшпиль!";
}
